export async function generateConnectionArtifacts() {
  const { loadServerConfigs } = await import("./config.js")
  const serverConfigs = await loadServerConfigs()

  const files = await readdir(SCHEMAS_DIR).catch(() => [] as string[])
  const schemaFiles = files.filter((f) => f.endsWith(".json"))

  if (schemaFiles.length === 0) {
    console.log("[typegen] No schemas found in .jig/schemas/. Connect a server first.")
    return
  }

  await mkdir(TYPES_DIR, { recursive: true })
  await mkdir(CONNECTIONS_DIR, { recursive: true })

  const servers: string[] = []

  for (const file of schemaFiles) {
    const serverName = file.replace(".json", "")
    const tools: Tool[] = await Bun.file(join(SCHEMAS_DIR, file)).json()

    // Type declaration surface — used for authoring context and mirrored next
    // to the runtime module for IDE / tooling consumers.
    const typesContent = generateTypeDeclaration(serverName, tools)
    await Bun.write(join(TYPES_DIR, `${serverName}.d.ts`), typesContent)
    await Bun.write(join(CONNECTIONS_DIR, `${serverName}.d.ts`), typesContent)

    // Runtime connection module — proxy or direct
    const cfg = serverConfigs[serverName]
    let runtimeContent: string
    if (cfg?.proxy?.connectDiscovery) {
      const { proxyCallCode } = await import(join(PROJECT_ROOT, cfg.proxy.connectDiscovery))
      runtimeContent = generateProxyRuntimeModule(serverName, tools, proxyCallCode)
    } else {
      runtimeContent = generateRuntimeModule(serverName, tools)
    }
    await Bun.write(join(CONNECTIONS_DIR, `${serverName}.ts`), runtimeContent)

    servers.push(serverName)
    console.log(`[typegen] ${serverName}: ${tools.length} tools${cfg?.proxy ? " (proxy)" : ""}`)
  }

  // Barrel exports
  const barrelExports = servers
    .map((s) => `export { ${s} } from "./${s}"`)
    .join("\n")

  await Bun.write(
    join(TYPES_DIR, "index.d.ts"),
    `// Auto-generated by jig typegen — do not edit\n${barrelExports}\n`
  )

  await Bun.write(
    join(CONNECTIONS_DIR, "index.ts"),
    `// Auto-generated by jig typegen — do not edit\n${barrelExports}\n`
  )

  await Bun.write(
    join(CONNECTIONS_DIR, "index.d.ts"),
    `// Auto-generated by jig typegen — do not edit\n${barrelExports}\n`
  )

  // Derive notification-capable-tools manifest from annotated schemas
  const { buildNotificationManifest } = await import("./discover/notification-manifest.js")
  const manifest = buildNotificationManifest()
  if (manifest.length > 0) {
    console.log(`[typegen] notification manifest: ${manifest.length} tool(s) — ${manifest.map(m => m.label).join(", ")}`)
  }

  console.log(`[typegen] Done. ${servers.length} server(s) ready.`)
}

async function main() {
  await generateConnectionArtifacts()
}

// Only run main() when executed directly, not when imported for testing
if (import.meta.main) {
  main()
}
