/**
 * Generates runtime connection modules + TypeScript declarations from cached MCP schemas.
 * Run after `jig connect <server>` to make tools available in jigs.
 *
 * Produces:
 *   .jig/types/{server}.d.ts        — type declarations for authoring context
 *   .jig/connections/{server}.ts    — runtime module with exact schema-derived tool types
 *   .jig/connections/{server}.d.ts  — matching declaration surface for the runtime module
 *   .jig/connections/index.ts       — barrel export of all connected servers
 *   .jig/connections/index.d.ts     — declaration barrel for the runtime modules
 *
 * Usage: bun run src/mcp/typegen.ts
 */
import { join } from "node:path"
import { pathToFileURL } from "node:url"
import { readdir, mkdir } from "node:fs/promises"
import type { Tool } from "@modelcontextprotocol/sdk/types.js"
import { CONNECTIONS_DIR, PROJECT_ROOT, SCHEMAS_DIR, TYPES_DIR } from "../config/paths.js"
import { firstLineSummary } from "../text.js"

const JS_RESERVED_WORDS = new Set([
  "break", "case", "catch", "class", "const", "continue", "debugger", "default", "delete",
  "do", "else", "export", "extends", "finally", "for", "function", "if", "import", "in",
  "instanceof", "new", "return", "super", "switch", "this", "throw", "try", "typeof",
  "var", "void", "while", "with", "yield", "enum", "await", "implements", "package",
  "protected", "static", "interface", "private", "public", "let",
])

function isSafeIdentifier(name: string): boolean {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) && !JS_RESERVED_WORDS.has(name)
}

export function toolNameToIdentifier(name: string): string {
  const normalized = name
    .replace(/[^A-Za-z0-9_$]+/g, "_")
    .replace(/_+/g, "_")
    .replace(/^_+|_+$/g, "")
  const base = normalized || "tool"
  const prefixed = /^[A-Za-z_$]/.test(base) ? base : `_${base}`
  return JS_RESERVED_WORDS.has(prefixed) ? `_${prefixed}` : prefixed
}

function renderTsPropertyName(name: string): string {
  return isSafeIdentifier(name) ? name : JSON.stringify(name)
}

function sourceFileUrl(path: string): string {
  return pathToFileURL(join(PROJECT_ROOT, path)).href
}

function runtimeImports(): string {
  return `import { getServerConfig } from "${sourceFileUrl("src/mcp/config.ts")}"
import { connectServer, callTool, registerConnection, shouldReconnectMcpConnection } from "${sourceFileUrl("src/mcp/client.ts")}"
import { buildDryRunToolResult, isDryRun, shouldStubToolInDryRun } from "${sourceFileUrl("src/sdk/dryrun.ts")}"
import { runContext } from "${sourceFileUrl("src/sdk/context.ts")}"
import type { JigTool } from "${sourceFileUrl("src/sdk/jig.ts")}"`
}

function jsonSchemaTypeToTS(prop: any): string {
  if (prop.enum) {
    return prop.enum.map((v: string) => `"${v}"`).join(" | ")
  }

  switch (prop.type) {
    case "string":
      return "string"
    case "number":
    case "integer":
      return "number"
    case "boolean":
      return "boolean"
    case "array":
      if (prop.items?.type === "string") return "string[]"
      if (prop.items?.type === "number" || prop.items?.type === "integer") return "number[]"
      return "unknown[]"
    case "object":
      return "Record<string, unknown>"
    default:
      return "unknown"
  }
}

function generateToolParams(tool: Tool): string {
  const schema = tool.inputSchema as any
  if (!schema?.properties || Object.keys(schema.properties).length === 0) {
    return "{}"
  }

  const requiredSet = new Set<string>(schema.required ?? [])
  const lines: string[] = []

  for (const [name, prop] of Object.entries(schema.properties) as [string, any][]) {
    const isRequired = requiredSet.has(name)
    const tsType = jsonSchemaTypeToTS(prop)
    const desc = prop.description ? ` /** ${prop.description.replace(/\*\//g, "* /")} */\n    ` : ""
    const opt = isRequired ? "" : "?"
    lines.push(`${desc}${renderTsPropertyName(name)}${opt}: ${tsType}`)
  }

  return `{ ${lines.join("; ")} }`
}

function generateRuntimeParamAliases(tools: Tool[]): string {
  return tools
    .map((tool) => `type ${toolNameToIdentifier(tool.name)}_params = ${generateToolParams(tool)}`)
    .join("\n\n")
}

export function generateTypeDeclaration(serverName: string, tools: Tool[]): string {
  const exampleTool = tools[0] ? toolNameToIdentifier(tools[0].name) : "tool_name"
  const lines: string[] = [
    `// Auto-generated by jig typegen — do not edit`,
    `// In jig code, import the connection object and call tools through it:`,
    `// import { ${serverName} } from "@jig/connections/${serverName}.js"`,
    `// Example: await ${serverName}.${exampleTool}({ ... })`,
    `// Do not call these declarations as globals.`,
    `import type { JigTool } from "../../src/sdk/jig"`,
    ``,
    `export declare function closeConnection(): Promise<void>`,
    ``,
  ]

  for (const tool of tools) {
    const desc = firstLineSummary(tool.description).replace(/\*\//g, "* /")
    const params = generateToolParams(tool)
    const identifier = toolNameToIdentifier(tool.name)
    lines.push(`  /** ${desc} */`)
    lines.push(`export declare const ${identifier}: JigTool<${params}, any>`)
    lines.push(``)
  }

  lines.push(`export declare const ${serverName}: {`)
  for (const tool of tools) {
    const identifier = toolNameToIdentifier(tool.name)
    lines.push(`  ${identifier}: typeof ${identifier}`)
    if (identifier !== tool.name) {
      lines.push(`  ${JSON.stringify(tool.name)}: typeof ${identifier}`)
    }
  }
  lines.push(`}`)
  return lines.join("\n")
}

export function generateRuntimeModule(serverName: string, tools: Tool[]): string {
  const readOnlySet = new Set(tools.filter(t => (t as any).annotations?.readOnlyHint).map(t => t.name))
  const typeAliases = generateRuntimeParamAliases(tools)
  const toolLines = tools.map(t =>
    `export const ${toolNameToIdentifier(t.name)} = tool<${toolNameToIdentifier(t.name)}_params, any>("${t.name}", ${readOnlySet.has(t.name)})`
  )
  const objectEntries = tools.flatMap((tool) => {
    const identifier = toolNameToIdentifier(tool.name)
    return identifier === tool.name
      ? [identifier]
      : [`${identifier}`, `${JSON.stringify(tool.name)}: ${identifier}`]
  })

  return `// Auto-generated by jig typegen — do not edit
${runtimeImports()}

${typeAliases}

let _pending: Promise<any> | null = null
async function conn() {
  if (!_pending) {
    _pending = (async () => {
      const cfg = await getServerConfig("${serverName}")
      const c = await connectServer("${serverName}", cfg)
      registerConnection("${serverName}", c)
      return c
    })()
  }
  return _pending
}

export async function closeConnection() {
  if (_pending) {
    try {
      const c = await _pending
      await c.transport.close().catch(() => {})
      await c.client.close().catch(() => {})
    } catch {}
    _pending = null
  }
}

async function invokeWithReconnect<T>(run: () => Promise<T>): Promise<T> {
  try {
    return await run()
  } catch (error) {
    if (!shouldReconnectMcpConnection(error)) throw error
    await closeConnection()
    return run()
  }
}

function tool<TInput extends Record<string, unknown>, TOutput = any>(name: string, readOnly: boolean): JigTool<TInput, TOutput> {
  const fn = async (params: TInput) => {
    const ctx = runContext.getStore()
    if (ctx && !ctx.isToolAllowedInCurrentStep(name)) {
      throw new Error(
        \`Tool "${serverName}.\${name}" is not allowed in step "\${ctx.currentStepLabel ?? "(no active step)"}". \`
        + \`Declare it in the tools array of your ctx.step() call.\`
      )
    }
    if (isDryRun() && !readOnly) {
      ctx?.output(\`[dry-run] Would call ${serverName}.\${name} with \${JSON.stringify(params ?? {})}\`)
      return buildDryRunToolResult(name, params ?? {}, readOnly) as TOutput
    }
    if (isDryRun() && readOnly && shouldStubToolInDryRun(params)) {
      ctx?.output(\`[dry-run] Skipping ${serverName}.\${name} because its params depend on a skipped tool result\`)
      return buildDryRunToolResult(name, params ?? {}, readOnly) as TOutput
    }
    return invokeWithReconnect(async () => (
      await callTool(await conn(), name, (params ?? {}) as Record<string, unknown>)
    ) as TOutput)
  }
  fn._serverName = "${serverName}"
  fn._toolName = name
  fn._readOnly = readOnly
  return fn as JigTool<TInput, TOutput>
}

${toolLines.join("\n")}

export const ${serverName} = { ${objectEntries.join(", ")} }
`
}

